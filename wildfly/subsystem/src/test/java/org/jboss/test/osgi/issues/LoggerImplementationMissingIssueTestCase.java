package org.jboss.test.osgi.issues;

import static org.junit.Assert.fail;

import org.jboss.logging.BasicLogger;
import org.jboss.logging.Logger;
import org.jboss.logging.Messages;
import org.junit.Test;

/**
 * Built on JDK 23 or later (JDK 25, JDK 27), the jboss-logging message interfaces of jbosgi have no
 * implementation, so the first log statement or message fails with ExceptionInInitializerError.
 *
 * <h2>Severity</h2>
 * critical. The user requires Java 25. Every jar of the stack built with the user's JDK 25 (or the default
 * JDK 27 {@code mvn}) is unusable: vfs, deployment and resolver fail their own tests, and the framework does not start.
 * The build still reports BUILD SUCCESS when test failures are ignored, and javac 25 prints no warning.
 *
 * <h2>Component</h2>
 * jbosgi, module wildfly/subsystem, interfaces OSGiLogger, OSGiMessages; build configuration in jbosgi-parent/pom.xml
 * (maven-compiler-plugin). All modules that declare jboss-logging message interfaces have the same problem:
 * <ul>
 <li>jbosgi-vfs/api: VFSLogger, VFSMessages</li>
 <li>jbosgi-spi: SPILogger, SPIMessages</li>
 <li>jbosgi-deployment: DeploymentLogger, DeploymentMessages</li>
 <li>jbosgi-resolver/api: ResolverLogger, ResolverMessages</li>
 <li>jbosgi-framework/core: FrameworkLogger, FrameworkMessages</li>
 <li>jbosgi-repository/core: RepositoryLogger, RepositoryMessages</li>
 <li>jbosgi-provision/core: ProvisionLogger, ProvisionMessages</li>
 <li>jbosgi/wildfly/subsystem: OSGiLogger, OSGiMessages</li>
 <li>jbosgi/wildfly/integration/http: WebLogger (no tests in that module)</li>
</ul>
 *
 * <h2>Found by</h2>
 * Tests workstream, JDK 27/25 run of the full r8 test suites. On JDK 21 every suite passes. On JDK 25 and 27:
 * jbosgi-vfs 13 errors, jbosgi-deployment 3, jbosgi-resolver 2+44, framework hangs, all with
 * "IllegalArgumentException: Invalid logger interface ... (implementation not found)".
 *
 * <h2>Spec reference</h2>
 * Not an OSGi spec issue. JDK 23 release note, JDK-8321314 "javac: Annotation processing is disabled by default"
 * (https://www.oracle.com/java/technologies/javase/23-relnote-issues.html#JDK-8321314): "As of JDK 23, annotation
 * processing is only run with some explicit configuration of annotation processing or with an explicit request
 * to run annotation processing on the javac command line." JDK 21 already warned during the baseline build:
 * "Annotation processing is enabled because one or more processors were found on the class path. A future
 * release of javac may disable annotation processing unless at least one processor is specified by name
 * (-processor), or a search path is specified (--processor-path, --processor-module-path), or annotation
 * processing is enabled explicitly (-proc:only, -proc:full)."
 *
 * <h2>Code location</h2>
 * jbosgi-parent/pom.xml:525-534 (maven-compiler-plugin configuration: source/target 21, no {@code <proc>},
 * no {@code annotationProcessorPaths}); the processor org.jboss.logging:jboss-logging-processor:3.0.4.Final is only
 * a provided dependency on the class path. Same configuration on origin/WF41 (jbosgi-parent 4.6.0): pre-existing.
 * Commit 7786fb3 ("require the Java version that the build targets") changed the enforcer rule to [21,), which
 * accepts JDK 23+ without making the build work on it.
 *
 * <h2>Root cause</h2>
 * The {@code *_$logger} and {@code *_$bundle} classes are generated by the jboss-logging annotation processor.
 * javac 23+ no longer runs processors that are only discovered on the class path, so they are silently not generated.
 * {@code Logger.getMessageLogger} / {@code Messages.getBundle} then throw IllegalArgumentException, which surfaces as
 * ExceptionInInitializerError / NoClassDefFoundError of the interface's static LOGGER / MESSAGES field.
 * The umbrella module wildfly/integration/http has the same problem for org.jboss.as.osgi.httpservice.WebLogger, but has no tests and no junit dependency, so it is not covered here.
 *
 * <h2>Reproduction</h2>
 * Only fails when the module is compiled on JDK 23+ without -proc:full (passes on JDK 21, and on JDK 25 with
 * {@code -Dmaven.compiler.proc=full}). From the repository root:
 * <pre>
 * JAVA_HOME=/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home mvn clean install -DskipTests
 * JAVA_HOME=/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home mvn -pl wildfly/subsystem test -Dtest=LoggerImplementationMissingIssueTestCase
 * </pre>
 *
 * <h2>Observed</h2>
 * <pre>
 * Tests run: 2, Failures: 2, Errors: 0, Skipped: 0, Time elapsed: 0.144 s <<< FAILURE! -- in org.jboss.test.osgi.issues.LoggerImplementationMissingIssueTestCase
org.jboss.test.osgi.issues.LoggerImplementationMissingIssueTestCase.testOSGiLogger
java.lang.AssertionError: Expected the generated implementation org.jboss.as.osgi.OSGiLogger_$logger of OSGiLogger in the build output, but it is missing (annotation processing did not run)
org.jboss.test.osgi.issues.LoggerImplementationMissingIssueTestCase.testOSGiMessages
java.lang.AssertionError: Expected the generated implementation org.jboss.as.osgi.OSGiMessages_$bundle of OSGiMessages in the build output, but it is missing (annotation processing did not run)
 * </pre>
 *
 * <h2>Expected</h2>
 * Every message interface has its generated implementation; the logger and bundle can be obtained.
 *
 * <h2>Reference behaviour</h2>
 * n/a (build issue).
 *
 * <h2>Suggested fix</h2>
 * In jbosgi-parent/pom.xml, maven-compiler-plugin configuration: either {@code <proc>full</proc>} (or the property
 * {@code <maven.compiler.proc>full</maven.compiler.proc>}), or better
 * {@code <annotationProcessorPaths><path><groupId>org.jboss.logging</groupId><artifactId>jboss-logging-processor</artifactId>
 * <version>${version.jboss.logging.processor}</version></path></annotationProcessorPaths>}. The umbrella repository jbosgi
 * inherits from the same parent. Optionally raise the enforcer upper bound only after this is fixed.
 *
 * <h2>Regression vs WF41</h2>
 * no (pre-existing, same compiler configuration on WF41); it becomes blocking with the move to Java 25.
 */
public class LoggerImplementationMissingIssueTestCase {

    @Test
    public void testOSGiLogger() throws Exception {
        Class<?> iface = Class.forName("org.jboss.as.osgi.OSGiLogger", false, getClass().getClassLoader());
        assertGenerated(iface, "_$logger");
        try {
            Logger.getMessageLogger(iface.asSubclass(BasicLogger.class), "issues");
        } catch (IllegalArgumentException ex) {
            fail("Expected a message logger for OSGiLogger, but got: " + ex);
        }
    }

    @Test
    public void testOSGiMessages() throws Exception {
        Class<?> iface = Class.forName("org.jboss.as.osgi.OSGiMessages", false, getClass().getClassLoader());
        assertGenerated(iface, "_$bundle");
        try {
            Messages.getBundle(iface);
        } catch (IllegalArgumentException ex) {
            fail("Expected a message bundle for OSGiMessages, but got: " + ex);
        }
    }

    private static void assertGenerated(Class<?> iface, String suffix) {
        String impl = iface.getName() + suffix;
        try {
            Class.forName(impl, false, iface.getClassLoader());
        } catch (ClassNotFoundException ex) {
            fail("Expected the generated implementation " + impl + " of " + iface.getSimpleName()
                + " in the build output, but it is missing (annotation processing did not run)");
        }
    }
}
